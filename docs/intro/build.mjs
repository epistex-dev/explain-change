// node docs/intro/build.mjs
// Reads the bundled sample session and writes docs/intro/data.js, the only data the video shows.
// Every number and name on screen comes from DATA (see NOTES.md for the field behind each one).
import fs from 'node:fs'; import path from 'node:path'; import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const sample = JSON.parse(fs.readFileSync(path.join(here, '../../skills/explain-change/references/examples/portal-day.session.json'), 'utf8'));
if (sample.schema !== 'explain-session/1') throw new Error('unexpected schema ' + sample.schema);
const STATUS = ['done', 'done_needs_you', 'done_by_user', 'in_progress'];
const themes = sample.themes.map((t, i) => {
  if (!STATUS.includes(t.status)) throw new Error(`theme ${t.id}: status ${t.status} has no colour and icon in index.html`);
  return {n: i + 1, id: t.id, title: t.title, status: t.status, events: t.events.length};
});
const kinds = {};
for (const t of sample.themes) for (const e of t.events) kinds[e.kind] = (kinds[e.kind] || 0) + 1;
const scratch = sample.outward.reduce((a, o) => a + (Number.isInteger(o.scratch) ? o.scratch : 0), 0);
const outTotal = sample.outward.reduce((a, o) => a + o.count, 0);
const data = {
  title: sample.title,
  themes,
  events: themes.reduce((a, t) => a + t.events, 0),
  blocked: kinds.blocked || 0,
  redirected: kinds.redirected || 0,
  decided: sample.decided.length,
  irreversible: sample.decided.filter(d => d.reversible === false).length,
  outward: {total: outTotal, kinds: sample.outward.length, scratch, listed: outTotal - scratch},
  statusCount: Object.fromEntries(STATUS.map(s => [s, themes.filter(t => t.status === s).length])),
};
fs.writeFileSync(path.join(here, 'data.js'), '/* generated by build.mjs from portal-day.session.json; do not edit */\nconst DATA = ' + JSON.stringify(data, null, 1) + ';\n');
console.log(JSON.stringify(data));
